/**
 * Migration: Convert session columns from ENUM to VARCHAR(50)
 * 
 * This enables custom session names (e.g., "Night", "Lunch Slot") 
 * instead of being limited to the 4 hardcoded ENUM values.
 * 
 * Run: node server/scripts/migrate-session-to-string.js
 */
const sequelize = require("../db");

async function migrate() {
  console.log("🔧 Migrating session columns from ENUM to VARCHAR(50)...\n");

  try {
    // Step 1: Change Bookings.session from ENUM to VARCHAR
    console.log("1. Altering Bookings.session...");
    await sequelize.query(`
      ALTER TABLE "Bookings" 
      ALTER COLUMN "session" TYPE VARCHAR(50) 
      USING "session"::VARCHAR(50);
    `);
    console.log("   ✅ Bookings.session → VARCHAR(50)");

    // Step 2: Change Enquiries.session from ENUM to VARCHAR
    console.log("2. Altering Enquiries.session...");
    await sequelize.query(`
      ALTER TABLE "Enquiries" 
      ALTER COLUMN "session" TYPE VARCHAR(50) 
      USING "session"::VARCHAR(50);
    `);
    console.log("   ✅ Enquiries.session → VARCHAR(50)");

    // Step 3: Drop the old ENUM types (they're auto-generated by Sequelize)
    console.log("3. Dropping old ENUM types...");
    try {
      await sequelize.query(`DROP TYPE IF EXISTS "enum_Bookings_session" CASCADE;`);
      console.log("   ✅ Dropped enum_Bookings_session");
    } catch(e) { console.log("   ⚠️  enum_Bookings_session not found (already removed)"); }
    
    try {
      await sequelize.query(`DROP TYPE IF EXISTS "enum_Enquiries_session" CASCADE;`);
      console.log("   ✅ Dropped enum_Enquiries_session");
    } catch(e) { console.log("   ⚠️  enum_Enquiries_session not found (already removed)"); }

    console.log("\n✅ Migration complete! Session columns now accept any string value.");
    process.exit(0);
  } catch (err) {
    console.error("\n❌ Migration failed:", err.message);
    process.exit(1);
  }
}

migrate();
