export const generateStatement = (data) => {
  const doc = new jsPDF();
  const { booking, payments } = data;
  
  drawHeader(doc, "CUSTOMER STATEMENT", booking);
  
  doc.setTextColor(...textDark);
  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text(`Booking Ledger Statement`, 14, 55);
  
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text(`Customer: ${booking.Customer?.name || booking.customerName}`, 14, 65);
  doc.text(`Date Generated: ${new Date().toLocaleDateString()}`, 14, 72);

  const statementBody = [
    [
      new Date(booking.date).toLocaleDateString(),
      "Booking Finalized (Gross Amount)",
      `Rs. ${booking.totalAmount?.toLocaleString() || 0}`,
      "-",
      `Rs. ${booking.totalAmount?.toLocaleString() || 0}`
    ]
  ];

  let runningBalance = booking.totalAmount || 0;
  
  if (payments && payments.length > 0) {
    const sortedPayments = [...payments].sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));
    sortedPayments.forEach(p => {
      runningBalance -= p.amount;
      statementBody.push([
        new Date(p.createdAt).toLocaleDateString(),
        `Receipt #${p.Receipt?.receiptNumber || "-"} (${p.paymentMode})`,
        "-",
        `Rs. ${Number(p.amount || 0).toLocaleString()}`,
        `Rs. ${Number(runningBalance || 0).toLocaleString()}`
      ]);
    });
  }
  
    autoTable(doc, {
    startY: 85,
    headStyles: { fillColor: primaryColor, textColor: 255 },
    head: [["Date", "Particulars", "Debit", "Credit", "Balance"]],
    body: statementBody,
    theme: "grid"
  });
  
  drawFooter(doc);
  // Open in new tab instead of silent download
  window.open(doc.output('bloburl'), '_blank');
};

