  doc.setFont("helvetica", "bold");
  doc.text(`${payment.paymentMode || "Cash"} ${payment.referenceNumber ? `(Ref: ${payment.referenceNumber})` : ""}`, 65, 110);
  doc.setDrawColor(200, 200, 200);
