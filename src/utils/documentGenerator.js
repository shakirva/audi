export const generateInvoice = (data) => {
  try {
  const doc = new jsPDF();
  const { booking, payments, totalPaid, outstanding } = data;
  
  drawHeader(doc, "FINAL TAX INVOICE", booking);
  
  // Invoice Info
  doc.setTextColor(...textDark);
  doc.setFontSize(11);
  doc.setFont("helvetica", "bold");
  doc.text("Bill To:", 14, 55);
  doc.setFont("helvetica", "normal");
  doc.text(`${booking.Customer?.name || booking.customerName || "Customer"}`, 14, 62);
  doc.text(`Phone: ${booking.Customer?.phone || booking.phone || "N/A"}`, 14, 68);
  
  doc.setFont("helvetica", "bold");
  doc.text("Invoice Details:", 120, 55);
  doc.setFont("helvetica", "normal");
  doc.text(`Status: ${outstanding <= 0 ? "PAID" : "DUE"}`, 120, 62);
  doc.text(`Date: ${new Date().toLocaleDateString()}`, 120, 68);

  // Summary Table
  doc.autoTable({
    startY: 80,
    headStyles: { fillColor: primaryColor, textColor: 255 },
    head: [["Item Description", "Amount (INR)"]],
    body: [
      [`Event Booking: ${booking.eventType || "Event"} at ${booking.hall || "Venue"}`, `Rs. ${Number(booking.totalAmount || 0).toLocaleString()}`]
    ],
    foot: [
      ["Gross Total", `Rs. ${Number(booking.totalAmount || 0).toLocaleString()}`],
      ["Total Paid", `Rs. ${Number(totalPaid || 0).toLocaleString()}`],
      ["Balance Due", `Rs. ${Number(outstanding || 0).toLocaleString()}`]
    ],
    footStyles: { fillColor: [248, 250, 252], textColor: textDark, fontStyle: "bold" },
    theme: "grid"
  });

  // Payment History
  if (payments && payments.length > 0) {
    const startY = (doc.lastAutoTable ? doc.lastAutoTable.finalY : 100) + 15;
    doc.text("Payment History", 14, startY);
    const payBody = payments.map(p => {
      let dateStr = "";
      try { dateStr = new Date(p.paymentDate || p.createdAt || Date.now()).toLocaleDateString(); } catch(e) { dateStr = "-"; }
      return [
        dateStr,
        p.Receipt?.receiptNumber || p.referenceNumber || "-",
        p.paymentMode || "Cash",
        `Rs. ${Number(p.amount || 0).toLocaleString()}`
      ];
    });
    
    doc.autoTable({
      startY: startY + 5,
      headStyles: { fillColor: [100, 116, 139] },
      head: [["Date", "Receipt No", "Mode", "Amount"]],
      body: payBody,
      theme: "grid"
    });
  }

  drawFooter(doc);
  doc.save(`Final_Invoice_${booking.bookingNumber || booking.id || "001"}.pdf`);
  } catch (err) {
    console.error(err);
    alert("PDF Error: " + err.message);
  }
};

